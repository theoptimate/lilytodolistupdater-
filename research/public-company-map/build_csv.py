def money(n):
    if n is None: return ""
    if abs(n) >= 1e12: return f"${n/1e12:.3f}T"
    if abs(n) >= 1e9: return f"${n/1e9:.2f}B"
    if abs(n) >= 1e6: return f"${n/1e6:.1f}M"
    return f"${n:.0f}"

def gm(t):
    r = Q.get(t) or {}
    bits = []
    for y in (2023, 2024, 2025):
        v = r.get(f"gm_{y}")
        if isinstance(v, float):
            bits.append(f"FY{y} {100*v:.1f}%")
    return "; ".join(bits)

def merge_us(t, extra):
    r = Q.get(t) or {}
    out = dict(extra)
    out.setdefault("ticker", t)
    out.setdefault("listing_verified", "yes" if r else extra.get("listing_verified",""))
    out.setdefault("access_date", "2026-09-02")
    out.setdefault("dropped", "")
    out.setdefault("drop_reason", "")
    out.setdefault("iv_vs_1y_range", "not in the record")
    if r:
        out.setdefault("name", (r.get("name") or "").replace(" Common Stock","").replace(" Class A common stock","").replace(" Ordinary Shares","").strip())
        out.setdefault("exchange", r.get("exchange") or "")
        out.setdefault("market_cap", money(r.get("market_cap_usd")))
        out.setdefault("market_cap_date", r.get("quote_ts") or "")
        out.setdefault("market_cap_source_url", r.get("source_url") or "")
        out.setdefault("gm_trend_3y", gm(t) or extra.get("gm_trend_3y",""))
        if r.get("cash"):
            out.setdefault("net_cash_or_debt", f"cash {money(r['cash'])} at {r.get('cash_end') or ''} (XBRL; debt not netted unless noted)")
        si = r.get("short_interest_shares")
        if si:
            out.setdefault("short_interest", f"{si} shares, {r.get('short_days_to_cover')} days, settlement {r.get('short_si_date')}")
        if r.get("options_listed"):
            out.setdefault("options_listed", r["options_listed"])
            out.setdefault("leaps", f"chain records {r.get('options_chain_records')}; LEAP expiries not fully enumerated except MU through 2028-12-15")
        if r.get("adv_usd"):
            out.setdefault("adv_usd", money(r["adv_usd"]))
        if r.get("analyst_target"):
            out.setdefault("analyst_count", extra.get("analyst_count") or f"1y target {r['analyst_target']} (count not always on Nasdaq summary)")
    for c in COLS:
        out.setdefault(c, "")
    return {c: out.get(c, "") for c in COLS}

